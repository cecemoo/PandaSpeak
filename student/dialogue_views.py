"""Dialogue listening practice: categories -> topics -> listen & answer.

Content lives in student/dialogue_data.py; audio files are generated by the
`generate_dialogue_audio` management command into
student/static/student/dialogues/<topic>-<l2|l3>.mp3.

Access: Level II and Level III students (the dashboard card is locked for
Level I, following the Cultural Insights / Chinese History pattern), and a
Plus feature — students with Plus can play every dialogue. A student
without Plus may claim ONE free dialogue (the first topic they open, kept
in DialogueFreePlay) and replay it any time; opening any other topic sends
them to the Plus upgrade page, the same pattern Chinese History uses.
"""
from django.http import Http404
from django.shortcuts import redirect, render

from subscription.plan_access import is_plus

from .dialogue_data import CATEGORIES, TOPICS
from .models import DialogueFreePlay

LEVEL_LABELS = {'level2': 'Level II', 'level3': 'Level III'}
LEVEL_SUFFIX = {'level2': 'l2', 'level3': 'l3'}

_CATEGORIES = {c['slug']: c for c in CATEGORIES}
_TOPICS = {t['slug']: t for t in TOPICS}


def _level_key(user):
    level = getattr(user, 'learning_level', '') or ''
    return level if level in LEVEL_LABELS else None


def _free_topic(user):
    """The topic dict of the user's claimed free dialogue, or None."""
    free = DialogueFreePlay.objects.filter(student=user).first()
    if free is None:
        return None
    return _TOPICS.get(free.topic_slug)


def _access_context(request):
    plus = is_plus(request.user)
    free_topic = None if plus else _free_topic(request.user)
    return {
        'dialogue_plus': plus,
        'dialogue_free_topic': free_topic,
    }


def dialogue_categories(request):
    level = _level_key(request.user)
    categories = []
    if level:
        for category in CATEGORIES:
            count = sum(
                1 for t in TOPICS
                if t['category'] == category['slug'] and level in t['versions'])
            if count:
                categories.append({**category, 'topic_count': count})
    context = {
        'dialogue_level': level,
        'dialogue_level_label': LEVEL_LABELS.get(level, ''),
        'dialogue_categories': categories,
    }
    context.update(_access_context(request))
    return render(request, 'student/dialogue_categories.html', context)


def dialogue_topics(request, category_slug):
    category = _CATEGORIES.get(category_slug)
    if category is None:
        raise Http404('Unknown dialogue category')
    level = _level_key(request.user)
    access = _access_context(request)
    free_slug = None
    if access['dialogue_free_topic']:
        free_slug = access['dialogue_free_topic']['slug']
    topics = []
    if level:
        for topic in TOPICS:
            if topic['category'] == category_slug and level in topic['versions']:
                topics.append({
                    'slug': topic['slug'],
                    'title_en': topic['title_en'],
                    'title_zh': topic['title_zh'],
                    'setting': topic['setting'],
                    'speakers': [s['label'] for s in topic['speakers'].values()],
                    'question_count': len(topic['versions'][level]['questions']),
                    'is_free_pick': topic['slug'] == free_slug,
                    'plus_locked': (
                        not access['dialogue_plus']
                        and free_slug is not None
                        and topic['slug'] != free_slug),
                })
    context = {
        'dialogue_level': level,
        'dialogue_level_label': LEVEL_LABELS.get(level, ''),
        'dialogue_category': category,
        'dialogue_topics': topics,
    }
    context.update(access)
    return render(request, 'student/dialogue_topics.html', context)


def dialogue_play(request, topic_slug):
    topic = _TOPICS.get(topic_slug)
    if topic is None:
        raise Http404('Unknown dialogue topic')
    level = _level_key(request.user)
    if level is None or level not in topic['versions']:
        raise Http404('This dialogue is not available for your level')
    plus = is_plus(request.user)
    free_play = False
    if not plus:
        claimed = _free_topic(request.user)
        if claimed is None:
            DialogueFreePlay.objects.get_or_create(
                student=request.user, defaults={'topic_slug': topic_slug})
            free_play = True
        elif claimed['slug'] == topic_slug:
            free_play = True
        else:
            return redirect('plus_upgrade')
    version = topic['versions'][level]
    category = _CATEGORIES[topic['category']]
    transcript = [
        {'speaker': topic['speakers'][key]['label'], 'text': text}
        for key, text in version['lines']
    ]
    return render(request, 'student/dialogue_play.html', {
        'dialogue_level': level,
        'dialogue_level_label': LEVEL_LABELS[level],
        'dialogue_category': category,
        'dialogue_topic': topic,
        'dialogue_audio': f"student/dialogues/{topic['slug']}-{LEVEL_SUFFIX[level]}.mp3",
        'dialogue_questions': version['questions'],
        'dialogue_transcript': transcript,
        'dialogue_plus': plus,
        'dialogue_free_play': free_play,
    })
